export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const page = PAGES[slug];

  if (!page) {
    return {
      title: "Страница не найдена",
      description: "Запрашиваемая страница отсутствует.",
    };
  }

  return {
    title: `${page.title} — Aviatour.travel`,
    description: page.description,
  };
}

export default async function Page({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const page = PAGES[slug];

  if (!page) {
    notFound();
  }

  return (
    <main className="min-h-screen bg-[var(--color-bg-soft)] px-6 py-20 text-[var(--color-text)]">
      <div className="mx-auto max-w-4xl rounded-3xl border border-[var(--color-border)] bg-[var(--color-surface)] p-8 shadow-sm">
        <p className="mb-3 text-sm font-semibold uppercase tracking-[0.24em] text-[var(--color-primary)]">
          Aviatour.travel
        </p>
        <h1 className="text-3xl font-bold sm:text-4xl">{page.title}</h1>
        <p className="mt-4 text-lg text-[var(--color-text-muted)]">{page.description}</p>

        <div className="mt-8 space-y-3 text-[var(--color-text-muted)]">
          {page.body.map((text) => (
            <p key={text} className="leading-relaxed">{text}</p>
          ))}
        </div>

        {page.cta && (
          <div className="mt-8">
            <Link
              href={page.cta.href}
              className="inline-flex items-center rounded-xl bg-[var(--color-primary)] px-5 py-3 text-sm font-semibold text-white transition hover:bg-[var(--color-primary-dark)]"
            >
              {page.cta.label}
            </Link>
          </div>
        )}
      </div>
    </main>
  );
}
